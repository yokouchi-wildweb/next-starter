// src/features/feature-map.txt（ドメインの一覧）の中身を作る・比べる（純粋。フォルダの読み取りは workspace.featureListing、書き込みは apply）。
// ルートの地図 src/app/route-map.jsonl と対。src/features と src/features/core の全フォルダ（_ で始まるものを除く）を 1 行ずつ:
//   <domain>  <kind: business | core>  <domain.json: yes | no | ->  <generate: true | false | ->
// domain.json あり = generate の値（省略 = true、壊れた JSON は ?）、domain.json なし = 手で管理（-）。business も core も同じ（違いはフォルダだけ）。
// pnpm generate domain が書き込みの最後に書き直し、pnpm check domain がフォルダの増減・generate の切り替えのずれを見つける。
// fork の merge で衝突したら、どちらの版も採らずに pnpm generate domain -- --feature-map で作り直す

export const FEATURE_MAP_FILE = "src/features/feature-map.txt";

const HEADER = [
  "# feature-map: generated by `pnpm generate domain -- --feature-map` (pnpm generate domain rewrites it). DO NOT EDIT. merge conflict → rerun `pnpm generate domain -- --feature-map`",
  "# <domain>\t<kind: business | core>\t<domain.json: yes | no | ->\t<generate: true = pnpm generate domain rewrites it | false = hand-managed | ->",
];

/**
 * @param {{ business: { name: string, generate: boolean | null | "?" }[], core: { name: string, generate: boolean | null | "?" }[] }} listing
 *   generate = domain.json の generate（省略は true）、null = domain.json なし、"?" = 壊れた domain.json
 * @returns {string}
 */
export function buildFeatureMap(listing) {
  const row = (label, kind, generate) => (generate === null ? [label, kind, "no", "-"] : [label, kind, "yes", String(generate)]);
  const rows = [
    ...listing.business.map(({ name, generate }) => row(name, "business", generate)),
    ...listing.core.map(({ name, generate }) => row(`core/${name}`, "core", generate)),
  ];
  return `${[...HEADER, ...rows.map((row) => row.join("\t"))].join("\n")}\n`;
}

const bodyLines = (text) => text.split("\n").filter((line) => line && !line.startsWith("#"));

/**
 * @param {string} expected buildFeatureMap の結果
 * @param {string | null} actual 今のファイル（無ければ null）
 * @returns {string[]} ずれた行（+ = 実際にある / - = 一覧にだけある）。空なら一致
 */
export function featureMapDiff(expected, actual) {
  if (actual === null) return [`${FEATURE_MAP_FILE} がありません（pnpm generate domain -- --feature-map で作る）`];
  const want = bodyLines(expected);
  const have = bodyLines(actual);
  const haveSet = new Set(have);
  const wantSet = new Set(want);
  return [...want.filter((line) => !haveSet.has(line)).map((line) => `+ ${line}`), ...have.filter((line) => !wantSet.has(line)).map((line) => `- ${line}`)];
}
