// 生成物の検査(lib.ruleGenerated.mjs)の振る舞い。実行: pnpm test scripts/workflow/rules/ruleGenerated.test.mjs
import { test } from "node:test";
import assert from "node:assert/strict";
import { expandDomainGlob, hasGeneratedMark, outputFiles, outputsOutsidePaths } from "./lib.ruleGenerated.mjs";

test("印: 先頭 5 行の印の語だけを見る", () => {
  assert.ok(hasGeneratedMark("// AUTO-GENERATED by pnpm generate registry\nexport {}"));
  assert.ok(hasGeneratedMark("/* 自動生成: 直さない */"));
  assert.ok(!hasGeneratedMark("export const a = 1;\n"));
  assert.ok(!hasGeneratedMark("1\n2\n3\n4\n5\n// generated\n"));
});

test("ドメインの雛形: 作り直しの対象のドメインの名で埋める({route} も全部の画面には広げない)", () => {
  assert.deepEqual(expandDomainGlob("{dir}/hooks/use{Pascal}.ts", [{ dir: "src/domains/fooBar" }, { dir: "src/domains/core/baz" }]), [
    "src/domains/fooBar/hooks/useFooBar.ts",
    "src/domains/core/baz/hooks/useBaz.ts",
  ]);
  const [route] = expandDomainGlob("src/app/admin/(protected)/{route}/_screen/loader.ts", [{ dir: "src/domains/fooBar" }]);
  assert.ok(!route.includes("*") && !route.includes("{"), route);
  assert.deepEqual(expandDomainGlob("src/registry/x.ts", []), ["src/registry/x.ts"]);
});

test("出力の宣言 → ファイル: 文字列は every-run、generate:false のドメインのファイルは入らない", () => {
  const gates = [
    { gate: "structure/registry", outputs: ["src/registry/a.ts", { glob: "src/domains/**/plugs/messages/*.ts", kind: "write-once" }] },
    { gate: "structure/domain", outputs: [{ glob: "{dir}/entities/schema.ts", kind: "every-run" }] },
  ];
  const files = ["src/registry/a.ts", "src/domains/a/entities/schema.ts", "src/domains/off/entities/schema.ts", "src/domains/a/plugs/messages/m.ts"];
  const out = outputFiles(gates, files, [{ dir: "src/domains/a" }]);
  assert.deepEqual(out.map((e) => [e.glob, e.kind, e.domain, e.files]), [
    ["src/registry/a.ts", "every-run", false, ["src/registry/a.ts"]],
    ["src/domains/**/plugs/messages/*.ts", "write-once", false, ["src/domains/a/plugs/messages/m.ts"]],
    ["{dir}/entities/schema.ts", "every-run", true, ["src/domains/a/entities/schema.ts"]],
  ]);
  assert.equal(outputFiles([{ gate: "g", outputs: "x" }], [], [])[0].problems.length, 1);
});

test("ドメインの every-run は生成の計画が書くファイルだけ: 条件が偽のドメインの同じ名の手書きの部品は生成物と数えない", () => {
  const gates = [
    {
      gate: "structure/domain",
      outputs: [
        { glob: "{dir}/components/common/{Pascal}DetailModal.tsx", kind: "every-run" },
        { glob: "{dir}/seed.ts", kind: "write-once" },
      ],
    },
  ];
  const files = ["src/domains/on/components/common/OnDetailModal.tsx", "src/domains/off/components/common/OffDetailModal.tsx", "src/domains/off/seed.ts"];
  const domains = [{ dir: "src/domains/on" }, { dir: "src/domains/off" }];
  const planned = new Set(["src/domains/on/components/common/OnDetailModal.tsx"]);
  assert.deepEqual(outputFiles(gates, files, domains, planned).map((e) => e.files), [["src/domains/on/components/common/OnDetailModal.tsx"], ["src/domains/off/seed.ts"]]);
  // 計画なし(null) = 宣言の glob のまま
  assert.deepEqual(outputFiles(gates, files, domains)[0].files, ["src/domains/on/components/common/OnDetailModal.tsx", "src/domains/off/components/common/OffDetailModal.tsx"]);
});

test("generated の paths に当たらない宣言を挙げる", () => {
  const entries = [{ glob: "src/registry/a.ts" }, { glob: "{dir}/entities/schema.ts" }, { glob: "src/lib/x/generated/y.ts" }];
  assert.deepEqual(outputsOutsidePaths(entries, ["src/registry/**", "src/domains/**"]).map((e) => e.glob), ["src/lib/x/generated/y.ts"]);
});
